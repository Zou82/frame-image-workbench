async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('frame-workbench-drafts-v1')));
  await page.keyboard.press('Escape');
  await page.getByRole('textbox', { name: '搜索任务', exact: true }).fill('');
  await page.getByRole('button', { name: '紧凑列表', exact: true }).click();
  await page.getByRole('checkbox', { name: '全选筛选结果', exact: true }).check();
  check((await page.locator('.batch-selection').innerText()).includes('100'), 'Selection must span all4 pages');
  await page.getByRole('button', { name: '修改所选任务参数', exact: true }).click();
  await page.getByRole('combobox', { name: '统一模型', exact: true }).selectOption('gpt-image-2.5-sunburst');
  await page.getByRole('combobox', { name: '统一尺寸 / 比例', exact: true }).selectOption('1536x864');
  await page.getByRole('combobox', { name: '统一画质', exact: true }).selectOption('high');
  await page.getByRole('button', { name: '保存为新任务默认值', exact: true }).click();
  await page.getByRole('button', { name: '应用勾选参数', exact: true }).click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('frame-workbench-drafts-v1')).every(task => task.model === 'gpt-image-2.5-sunburst' && task.size === '1536x864' && task.quality === 'high'));
  check((await stored())[0].references.length > 0, 'Bulk edit must preserve references');
  await page.getByRole('button', { name: '清除选择', exact: true }).click();
  await page.getByRole('button', { name: '新建任务', exact: true }).click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('frame-workbench-drafts-v1')).length === 101);
  const added = (await stored()).at(-1);
  check(added.model === 'gpt-image-2.5-sunburst' && added.size === '1536x864' && added.quality === 'high', 'New tasks must inherit saved defaults');
  await page.getByRole('textbox', { name: '搜索任务', exact: true }).fill('创作 101');
  await page.getByRole('checkbox', { name: '全选筛选结果', exact: true }).check();
  await page.getByRole('button', { name: '移除所选任务', exact: true }).click();
  await page.getByRole('textbox', { name: '搜索任务', exact: true }).fill('批量任务 100');
  await page.getByRole('button', { name: '打开任务 100', exact: true }).click();
  await page.getByRole('combobox', { name: '任务 100 模型', exact: true }).selectOption('gateway-art-v2');
  if (!(await page.getByRole('button', { name: '2:3', exact: true }).count())) await page.getByRole('button', { name: '自定义', exact: true }).click();
  await page.getByRole('button', { name: '2:3', exact: true }).click();
  await page.getByRole('combobox', { name: '任务 100 画质', exact: true }).selectOption('low');
  await page.getByRole('button', { name: '关闭任务编辑', exact: true }).click();
  await page.getByRole('textbox', { name: '搜索任务', exact: true }).fill('');
  await page.getByRole('button', { name: '统一参数', exact: true }).click();
  await page.getByRole('checkbox', { name: '批量修改模型', exact: true }).uncheck();
  await page.getByRole('checkbox', { name: '批量修改尺寸 / 比例', exact: true }).uncheck();
  await page.getByRole('combobox', { name: '统一画质', exact: true }).selectOption('medium');
  await page.getByRole('button', { name: '应用勾选参数', exact: true }).click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('frame-workbench-drafts-v1')).every(task => task.quality === 'medium'));
  const last = (await stored()).at(-1);
  check(last.model === 'gateway-art-v2' && last.size === '1024x1536', 'Unchecked fields must preserve individual overrides');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'output/playwright/batch-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 1);
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile workbench overflows horizontally');
  await page.screenshot({ path: 'output/playwright/batch-mobile.png' });
  await page.getByRole('button', { name: '统一参数', exact: true }).click();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile defaults dialog overflows');
  await page.screenshot({ path: 'output/playwright/batch-mobile-settings.png' });
  await page.getByRole('button', { name: '关闭统一参数', exact: true }).click();
  await page.getByRole('button', { name: 'JSON 批量导入', exact: true }).click();
  await page.getByLabel('导入 JSON 文件', { exact: true }).setInputFiles({ name: 'batch.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ version: 1, tasks: [{ prompt: 'JSON file test' }] })) });
  check(await page.getByRole('button', { name: '导入草稿 (1)', exact: true }).isEnabled(), 'JSON file import must preview valid task');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载 JSON 示例', exact: true }).click();
  await (await download).saveAs('output/playwright/downloaded-batch-example.json');
  await page.getByRole('tab', { name: '给 AI 的提示词', exact: true }).click();
  const text = await page.getByRole('textbox', { name: '给 AI 的 JSON 生成提示词' }).inputValue();
  check(text.includes('1536x864') && !text.includes('fixture-only-key'), 'AI instruction must reflect defaults and omit credentials');
  await page.screenshot({ path: 'output/playwright/batch-mobile-import.png' });
  await page.getByRole('button', { name: '关闭导入', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.reload();
  check((await stored()).length === 100 && (await stored()).at(-1).model === 'gateway-art-v2', 'Refresh must preserve100 drafts and overrides');
  console.log('PASS: selected100 bulk update, defaults, new task inheritance, selective editing, individual overrides, mobile layout, JSON file/download, refresh persistence.');
}
